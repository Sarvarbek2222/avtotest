    /// <summary>
    /// Mavzu nomini tanlangan tilda qaytaradi (kalit — kirill nomi).
    /// Tarjimalar resx fayllarida: "topic.1" … "topic.42" (All[] tartibida).
    /// Ro'yxatda yo'q mavzu bo'lsa — kirill nomi lotinga o'giriladi.
    /// </summary>
    public static string Display(string? topic, string lang)
    {
        if (string.IsNullOrWhiteSpace(topic)) return "";
        topic = topic.Trim();

        var idx = Array.IndexOf(All, topic);
        if (idx >= 0) return Texts.Get(lang, "topic." + (idx + 1));

        return Lang.Normalize(lang) == Lang.Uzk ? topic : Translit.ToLatin(topic);
    }
